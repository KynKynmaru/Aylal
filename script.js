/* =====================================
   LOAD GEOJSON
===================================== */

fetch(GEOJSON_URL)

.then(response => {

    if (!response.ok) {
        throw new Error("GeoJSON ачааллахад алдаа гарлаа");
    }

    return response.json();
})

.then(data => {

    const geoLayer =
        L.geoJSON(
            data,
            {

                style: function() {

                    return {

                        className:
                            "province",

                        fillColor:
                            "#bdbdbd",

                        fillOpacity:
                            1,

                        color:
                            "#ffffff",

                        weight:
                            2
                    };
                },


                onEachFeature:
                function(feature, layer) {

                    let originalName =
                        feature.properties.prefecture
                        ||
                        feature.properties.name
                        ||
                        feature.properties.NAME
                        ||
                        feature.properties.NAME_1;


                    let cleanName =
                        String(originalName || "")
                            .trim();

                    let key =
                        nameMap[cleanName]
                        ||
                        nameMap[cleanName.toLowerCase()]
                        ||
                        cleanName;

                    /*
                       Төв аймаг GeoJSON дээр
                       Töv / Tov / Tuv / Төв
                       хэлбэрээр ирсэн ч ажиллана.
                    */

                    if (
                        cleanName === "Töv"
                        ||
                        cleanName === "Tov"
                        ||
                        cleanName === "Tuv"
                        ||
                        cleanName === "Төв"
                    ) {
                        key = "Tov";
                    }


                    layer.on(
                        "click",
                        function() {

                            selectProvince(
                                key,
                                layer
                            );

                        }
                    );

                }

            }
        )
        .addTo(map);


    map.fitBounds(
        geoLayer.getBounds(),
        {
            padding: [
                20,
                20
            ]
        }
    );

})

.catch(error => {

    console.error(
        "GeoJSON Error:",
        error
    );

});


/* =====================================
   SELECT PROVINCE
===================================== */

function selectProvince(
    key,
    layer
) {

    /*
       Өмнөх сонголтыг арилгах
    */

    document
        .querySelectorAll(".province")
        .forEach(el => {
            el.classList.remove(
                "selected"
            );
        });


    /*
       Одоогийн сонголтыг цэнхэр болгоно
    */

    if (layer.getElement()) {

        layer
            .getElement()
            .classList.add(
                "selected"
            );
    }


    /*
       Data
    */

    const info =
        provinceInfo[key];


    if (!info) {

        console.warn(
            "Province data олдсонгүй:",
            key
        );

        return;
    }


    /*
       Save visited
    */

    if (!visited.includes(key)) {

        visited.push(key);

        localStorage.setItem(
            "visitedProvinces",
            JSON.stringify(
                visited
            )
        );

    }


    updateCount();


    /*
       Quick information
    */


    /*
       Detail
    */

    showProvinceDetail(
        info,
        key
    );
}
/* =====================================
   COUNT
===================================== */

function updateCount() {

    document.getElementById(
        "visitedCount"
    ).innerText =
        "#" + visited.length;
}


